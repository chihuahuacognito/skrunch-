// Pure parts of the photo bundling script: which files to fetch and the generated require map.

const BASE = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/';

export interface ImageJob { id: string; frame: 0 | 1; url: string; out: string }

/** The start and end photo of every exercise that has at least two. */
export function imageJobs(lib: { id: string; images: string[] }[]): ImageJob[] {
  return lib
    .filter(e => e.images.length >= 2)
    .flatMap(e => ([0, 1] as const).map(frame => ({
      id: e.id, frame, url: BASE + e.images[frame], out: `assets/exercises/${e.id}/${frame}.jpg`,
    })));
}

/** src/ui/images.ts: literal require() calls, because Metro only bundles static requires. */
export function imageMapSource(ids: string[]): string {
  const rows = [...ids].sort().map(id =>
    `  '${id}': [require('../../assets/exercises/${id}/0.jpg'), require('../../assets/exercises/${id}/1.jpg')],`);
  return [
    '// Generated by scripts/images/fetch-images.ts - do not edit by hand.',
    '/* eslint-disable @typescript-eslint/no-require-imports */',
    'export const EXERCISE_IMAGES: Record<string, [number, number]> = {',
    ...rows,
    '};',
    '',
  ].join('\n');
}
