import { imageJobs, imageMapSource } from './plan';

const lib = [
  { id: 'Barbell_Squat', images: ['Barbell_Squat/0.jpg', 'Barbell_Squat/1.jpg'] },
  { id: 'bird-dog', images: [] },
  { id: 'One_Frame', images: ['One_Frame/0.jpg'] },
];

test('jobs cover the first two frames of exercises with two photos only', () => {
  expect(imageJobs(lib)).toEqual([
    { id: 'Barbell_Squat', frame: 0, url: 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/Barbell_Squat/0.jpg', out: 'assets/exercises/Barbell_Squat/0.jpg' },
    { id: 'Barbell_Squat', frame: 1, url: 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/Barbell_Squat/1.jpg', out: 'assets/exercises/Barbell_Squat/1.jpg' },
  ]);
});

test('the map source uses static requires Metro can bundle', () => {
  const src = imageMapSource(['Barbell_Squat']);
  expect(src).toContain("'Barbell_Squat': [require('../../assets/exercises/Barbell_Squat/0.jpg'), require('../../assets/exercises/Barbell_Squat/1.jpg')],");
  expect(src).toContain('export const EXERCISE_IMAGES: Record<string, [number, number]> = {');
  expect(src.startsWith('// Generated by scripts/images/fetch-images.ts')).toBe(true);
});
